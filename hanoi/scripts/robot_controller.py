    def execute_hanoi_move(self, source_peg, target_peg, viewer=None):
        """
        Executes a full pick-and-place sequence for a single abstract Hanoi move.
        """
        # 1. Identify which disk to move and determine heights from internal state
        if not self.peg_state[source_peg]:
            print(f"⚠️ Warning: Attempted to pick from empty peg {source_peg}. Skipping move.")
            return
            
        disk_to_move_body_name = self.peg_state[source_peg][-1]
        disk_id_str = disk_to_move_body_name.replace('disk_body', '')

        source_level = len(self.peg_state[source_peg])
        target_level = len(self.peg_state[target_peg]) + 1

        # Define the sequence of sites to target
        approach_site_src = f"post{source_peg}_approach"
        grasp_site = f"disk{disk_id_str}_grasp_top"
        place_site = f"post{target_peg}_level{target_level}"
        approach_site_tgt = f"post{target_peg}_approach"

        print(f"\n🤖 === EXECUTING MOVE: {disk_to_move_body_name} from peg {source_peg} to peg {target_peg} ===")
        print(f"   Source level: {source_level}, Target level: {target_level}")
        print(f"   ⚠️  NOTE: Using PLACEHOLDER movements with very slow, safe joint motions")

        # --- Execute Physical Movement Sequence ---
        # Move to a safe height above the source disk
        print(f"🔄 Step 1: Moving to approach position above peg {source_peg}...")
        self.move_to_pose(self.model.site(approach_site_src).pos, duration=8.0, viewer=viewer)
        print(f"✅ Reached approach position above peg {source_peg}")
        
        # Descend to grasp the disk (target the disk's moving site)
        # We get the site's position dynamically as the disk might have shifted
        grasp_pos = self.data.site(grasp_site).xpos
        print(f"🔄 Step 2: Descending to grasp {disk_to_move_body_name}...")
        self.move_to_pose(grasp_pos, duration=8.0, viewer=viewer)
        print(f"✅ Positioned above {disk_to_move_body_name}")
        
        # Grasp
        print(f"🔄 Step 3: Closing gripper to grasp {disk_to_move_body_name}...")
        self.set_gripper('closed', viewer=viewer)
        print(f"✅ Gripper closed - {disk_to_move_body_name} grasped")
        
        # Ascend back to the approach height
        print(f"🔄 Step 4: Lifting {disk_to_move_body_name} to safe height above peg {source_peg}...")
        self.move_to_pose(self.model.site(approach_site_src).pos, duration=6.0, viewer=viewer)
        print(f"✅ {disk_to_move_body_name} lifted to safe height")
        
        # Move to the approach height of the target peg
        print(f"🔄 Step 5: Moving {disk_to_move_body_name} to approach position above peg {target_peg}...")
        self.move_to_pose(self.model.site(approach_site_tgt).pos, duration=10.0, viewer=viewer)
        print(f"✅ Positioned above peg {target_peg}")
        
        # Descend to the correct level on the target peg
        print(f"🔄 Step 6: Descending to place {disk_to_move_body_name} at level {target_level} on peg {target_peg}...")
        self.move_to_pose(self.model.site(place_site).pos, duration=8.0, viewer=viewer)
        print(f"✅ Positioned at target placement location")
        
        # Release
        print(f"🔄 Step 7: Opening gripper to release {disk_to_move_body_name}...")
        self.set_gripper('open', viewer=viewer)
        print(f"✅ Gripper opened - {disk_to_move_body_name} released")
        
        # Ascend back to the approach height
        print(f"🔄 Step 8: Retracting to safe height above peg {target_peg}...")
        self.move_to_pose(self.model.site(approach_site_tgt).pos, duration=6.0, viewer=viewer)
        print(f"✅ Retracted to safe height")

        # --- Update Internal State ---
        moved_disk = self.peg_state[source_peg].pop()
        self.peg_state[target_peg].append(moved_disk)
        print(f"🎯 === MOVE COMPLETE: {disk_to_move_body_name} successfully moved from {source_peg} to {target_peg} ===")
        print(f"   Updated puzzle state: {self.peg_state}\n")