import mujoco
import numpy as np
import time

class RobotController:
    """
    A professional-grade controller for the Franka Emika Panda arm in MuJoCo.

    This controller uses a torque-based PID controller at the joint level to track
    trajectories generated by a differential inverse kinematics (IK) solver.
    This allows for smooth and precise control of the end-effector in Cartesian space.
    """
    def __init__(self, model, data, n_disks=3):
        """Initializes the RobotController."""
        self.model = model
        self.data = data
        self.n_disks = n_disks

        # --- Get MuJoCo IDs ---
        # Actuators
        self.actuator_names = [f'actuator{i+1}' for i in range(7)]
        self.arm_actuator_ids = np.array([mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, name) for name in self.actuator_names])
        self.gripper_actuator_id = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, "actuator8")

        # Joints
        self.joint_names = ['joint1', 'joint2', 'joint3', 'joint4', 'joint5', 'joint6', 'joint7']
        self.arm_joint_ids = np.array([mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_JOINT, name) for name in self.joint_names])

        # --- Internal State Tracking ---
        self.peg_state = {
            'A': [f'disk_body{i}' for i in range(self.n_disks, 0, -1)],
            'B': [],
            'C': []
        }
        
